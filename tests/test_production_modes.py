class NormalizationTests(unittest.TestCase):
    def test_nfkc_casefold_whitespace_and_punctuation(self):
        self.assertEqual(normalize_text(" ＡＢＣ，‘采访’！？\n"), "abc采访")
        self.assertEqual(normalize_text("Café"), normalize_text("Cafe\u0301"))
        self.assertEqual(normalize_text("\u1100\u1161"), normalize_text("가"))

    def test_dates_days_and_address_numbers(self):
        self.assertEqual(normalize_text("一月三十一号"), "1月31日")
        self.assertEqual(normalize_text("１月３１日"), "1月31日")
        self.assertEqual(normalize_text("二〇二六年九月二十八日"), "2026年9月28日")
        self.assertEqual(normalize_text("鲁班路九十五号"), "鲁班路95号")
        self.assertNotEqual(normalize_text("95号"), normalize_text("95日"))

    def test_chinese_numbers_units_and_financial_forms(self):
        cases = {"两百": "200", "兩百": "200", "一千零二十": "1020", "十": "10",
                 "十一": "11", "二十三": "23", "一万零三": "10003", "二亿三千万": "230000000",
                 "壹佰贰拾叁": "123", "貳佰參拾肆": "234", "伍佰陆拾柒": "567",
                 "捌仟玖佰": "8900", "三点五": "3.5", "负三点五": "-3.5"}
        for text, expected in cases.items():
            with self.subTest(text=text):
                self.assertEqual(normalize_text(text), expected)

    def test_numeric_sign_and_decimal_do_not_destroy_meaning(self):
        self.assertNotEqual(normalize_text("3.5元"), normalize_text("35元"))
        self.assertNotEqual(normalize_text("负三度"), normalize_text("三度"))

    def test_discourse_fillers_removed_without_substring_damage(self):
        self.assertEqual(normalize_text("嗯，啊，呃，那个，就是说，就是，然后我们欢迎大家"), "我们欢迎大家")
        self.assertEqual(normalize_text("嗯…就是希望大家来。"), "希望大家来")
        for text in ("那个人", "然后果很严重", "呃逆", "阿姨", "就是事实", "我们一直在一起", "千万别忘记"):
            with self.subTest(text=text):
                self.assertEqual(normalize_text(text), text)

    def test_mapping_covers_entire_multiword_number(self):
        text = "嗯，一月三十一号欢迎"
        value = pm._normalize_with_mapping(text)
        self.assertEqual(value.text, "1月31日欢迎")
        self.assertEqual(len(value.text), len(value.spans))
        left = value.text.index("3")
        self.assertEqual(text[slice(*value.spans[left])], "三十一")
        self.assertEqual(value.spans[left], value.spans[left + 1])

    def test_whitespace_inside_spoken_numbers_does_not_change_value(self):
        self.assertEqual(normalize_text("一 月 三 十 一 号"), "1月31日")
        self.assertEqual(normalize_text("两\n百零\t三"), "203")
        self.assertEqual(normalize_text("－ ３．５"), "-3.5")


