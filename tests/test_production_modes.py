def reference_distance(a: str, b: str) -> int:
    """Edit-distance oracle ONLY for _distance/text-difference, not §10.3."""
    grid = [[0] * (len(b) + 1) for _ in range(len(a) + 1)]
    for i in range(len(a) + 1):
        grid[i][0] = i
    for j in range(len(b) + 1):
        grid[0][j] = j
    for i in range(1, len(a) + 1):
        for j in range(1, len(b) + 1):
            grid[i][j] = min(grid[i - 1][j] + 1, grid[i][j - 1] + 1,
                             grid[i - 1][j - 1] + (a[i - 1] != b[j - 1]))
    return grid[-1][-1]


def reference_similarity(a: str, b: str) -> float:
    """Independent §10.3 on normalized strings; list removal, not Counter/code reuse."""
    if not a or not b:
        return 0.0
    if min(len(a), len(b)) == 1:
        return float(a in b or b in a)
    remaining = [b[i:i + 2] for i in range(len(b) - 1)]
    intersection = 0
    for i in range(len(a) - 1):
        gram = a[i:i + 2]
        if gram in remaining:
            remaining.remove(gram)
            intersection += 1
    return max(2 * intersection / (len(a) + len(b) - 2),
               intersection / min(len(a) - 1, len(b) - 1))


def reference_best(query: str, text: str, boundaries: tuple[int, ...] | None = None) -> float:
    """Exhaust every legal endpoint pair, retaining full precision."""
    points = boundaries if boundaries is not None else tuple(range(len(text) + 1))
    return max((reference_similarity(query, text[a:b])
                for a in points for b in points if b > a), default=0.0)


def assert_original_blocked(test: unittest.TestCase, requested: str, result: dict[str, Any]) -> None:
    """Raw lexical success cannot authorize C or fabricate contiguous evidence."""
    test.assertIsNotNone(result["source"])
    test.assertFalse(quote_text_is_contiguous(requested, result["source"]))
    for gate in ("warn", "block"):
        issues = evaluate_mode_checks([{**result, "text": requested}], [], "original", {}, gate)
        issue = next(v for v in issues if v["code"] == "QUOTE_NONCONTIGUOUS")
        test.assertEqual((issue["level"], issue["severity"]), (0, "error"))


