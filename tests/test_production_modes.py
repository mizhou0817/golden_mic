class IsolationTests(unittest.TestCase):
    def test_module_imports_only_stdlib_and_pydantic(self):
        tree = ast.parse(Path(pm.__file__).read_text(encoding="utf-8"))
        allowed = {"__future__", "hashlib", "json", "math", "re", "unicodedata", "bisect", "collections", "dataclasses", "decimal", "pathlib", "typing", "pydantic"}
        self.assertTrue(allowed - {"pydantic"} <= sys.stdlib_module_names)
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                self.assertTrue(all(alias.name.split(".")[0] in allowed for alias in node.names))
            elif isinstance(node, ast.ImportFrom):
                self.assertIn((node.module or "").split(".")[0], allowed)
                self.assertEqual(node.level, 0)

